 private void showQuestion() {


    switch (step) {

        case 0:
           ask.setText(
                "Does your mushroom have a convex cup?"
            );
            break;

        case 1:
          ask.setText(
                "Does your mushroom have a ring?"
            );
            break;

        case 2:
            ask.setText(
                "Does your mushroom grow in a forest?"
            );
            break;

        case 3:
            ask.setText(
                "Does your mushroom have gills?"
            );
            break;
    }
}
private void showResult(String mushroom) {
    ask.setText("Identification completed!");
    out.setText("Identified mushroom: " + mushroom);
    yes1.setEnabled(false);
    no1.setEnabled(false);
}

     




